def render(key, d, terms, index):
    first = d["start"]
    last = first + len(terms) - 1
    gp_lines, py_code, _ = PROGRAMS[key]
    out = [
        f"OEIS submission draft {index}/6: {key}  (batch {d['batch']})",
        "Paste each field into the form at https://oeis.org/Submit.html; upload the b-file as a link.",
        "The AUTHOR field is filled in by the form from your OEIS account.",
        "",
        "NAME", d["name"], "",
        "DATA", data_line(terms), "",
        "OFFSET", offset(first, terms), "",
        "COMMENTS", *d["comments"], "",
        "LINKS",
        f"Table of n, a(n) for n = {first}..{last}  [upload oeis/bfiles/b_{key}.txt]",
        *d["links"], "",
    ]
    if d["formula"]:
        out += ["FORMULA", *d["formula"], ""]
    out += [
        "EXAMPLE", *d["example"], "",
        "PROG",
        *(("(PARI) " if i == 0 else "") + l for i, l in enumerate(gp_lines)),
        "(Python)", *py_code.rstrip().splitlines(), "",
        "CROSSREFS", d["crossrefs"], "",
        "KEYWORD", d["keywords"], "",
    ]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--cmax", type=int, default=31)
    ap.add_argument("--a", action="append", default=[], metavar="KEY=A123456")
    ap.add_argument("--repo", default="https://github.com/C1aud1o/exclusion-arithmetic")
    ap.add_argument("--online", action="store_true")
    args = ap.parse_args()

    if args.online:
        try:
            cross_check_online()
        except OSError as error:
            require(False, f"online: could not fetch from oeis.org ({error})")
    T, compset, bits, source = compute_terms(args.cmax)
    A = dict(item.split("=") for item in args.a)
    require(set(A) <= set(T), f"unknown key in --a (keys: {', '.join(T)})")
    check_facts(T, compset, bits)
    programs = check_programs(T)
    drafts = build_drafts(T, A, args.repo)

    print(f"C(n) source: {source}\n")
    print(f"{'#':1} {'sequence':21} {'batch':5} {'offset':6} {'b-file':>12}  {'DATA':>9}  programs / status")
    for index, (key, d) in enumerate(drafts.items(), 1):
        terms = T[key]
        text = render(key, d, terms, index)
        data = data_line(terms)
        shown = [int(t) for t in data.split(", ")]
        bfile = "".join(f"{d['start'] + i} {t}\n" for i, t in enumerate(terms))
        require(text.isascii() and "\\boxplus" not in text and "$" not in text, f"{key}: non-ASCII or TeX in draft")
        require(len(data) <= DATA_LIMIT and shown == terms[: len(shown)], f"{key}: DATA line")
        require(len(terms) >= 1000 or key == "count_odd_composites", f"{key}: b-file shorter than 1000 terms")
        draft_path = ROOT / "oeis" / "drafts" / f"{index}_{key}.txt"
        bfile_path = ROOT / "oeis" / "bfiles" / f"b_{key}.txt"
        draft_path.write_text(text, encoding="utf-8", newline="\n")  # LF on every platform
        bfile_path.write_text(bfile, encoding="utf-8", newline="\n")
        require(b"\r" not in draft_path.read_bytes() + bfile_path.read_bytes(), f"{key}: CR in a written file")
        back = [int(line.split()[1]) for line in bfile_path.read_text(encoding="utf-8").splitlines()]
        require(back[: len(shown)] == shown and back == terms, f"{key}: b-file does not match DATA")
        pending = "A??????" in text
        require(not (pending and d["batch"] == 1), f"{key}: placeholder in a batch 1 draft")
        require(set(re.findall(r"A\?{6}\((\w+)\)", text)) <= set(BATCH1), f"{key}: placeholder for a batch 2 number")
        ready = "needs the batch 1 A-numbers (--a)" if pending else "READY"
        print(f"{index} {key:21} {d['batch']:^5} {offset(d['start'], terms):6} "
              f"{len(terms):6d} terms  {len(shown):3d} terms  {programs[key]}; {ready}")
        print(f"    first 12: {', '.join(map(str, terms[:12]))}")
    print()
    if problems:
        print("FAILED:\n  " + "\n  ".join(problems))
        return 1
    print("ALL DRAFTS AND B-FILES VERIFIED")
    return 0


if __name__ == "__main__":
    sys.exit(main())
