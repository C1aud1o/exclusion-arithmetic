DATA_LIMIT = 260
DEFINITION = (
    "Exclusion arithmetic: let S = N_0[x]/(2 = 1 + x) be the commutative semiring of polynomials "
    "with nonnegative integer coefficients modulo the congruence generated by 2 = 1 + x. Every "
    "class contains exactly one polynomial with all coefficients in {0, 1}; reading it in base 2 "
    "(x -> 2) identifies S with the nonnegative integers and equips them with a sum [+] and a "
    "product [x]. To compute, add or multiply the binary expansions as polynomials and then "
    "normalize from the least significant column upward: a column holding t >= 1 units keeps one "
    "unit and passes the other t - 1 to the next column (so 1 [+] 1 = 3 and 3 [x] 3 = 15)."
)

problems = []


def require(ok, what):
    if not ok:
        problems.append(what)


def ones(k):
    return (1 << k) - 1


def trunc(x, digits):
    """x truncated (not rounded) to the given number of decimals, with a trailing '...'."""
    return f"{floor(x * 10 ** digits) / 10 ** digits:.{digits}f}..."


def entropy(p):
    return -p * log2(p) - (1 - p) * log2(1 - p)


H = entropy(1 / 3)                       # = log2(3) - 2/3
BATCH1 = ("doubling", "squares", "odd_composites")
BOUNDS = {}                              # constants of the C(n) draft, filled in by check_facts
LAMBDA5 = 1.0                            # real root of x^5 = x^4 + x^3 + 1, by bisection
_hi = 2.0
for _ in range(200):
    _mid = (LAMBDA5 + _hi) / 2
    LAMBDA5, _hi = (_mid, _hi) if _mid ** 5 < _mid ** 4 + _mid ** 3 + 1 else (LAMBDA5, _mid)


def binary(n):
    return format(n, "b") + "_2"


def is_prime(n):
    return n > 1 and all(n % d for d in range(2, int(n ** 0.5) + 1))


def columns(coefficients):
    """Units held by each column during normalisation (carry included)."""
    held, c, k = [], 0, 0
    while k < len(coefficients) or c:
        t = c + (coefficients[k] if k < len(coefficients) else 0)
        held.append(t)
        c = max(t - 1, 0)
        k += 1
    return held


# --- terms -----------------------------------------------------------------------

def compute_terms(cmax):
    doubling = [eadd(n, n) for n in range(10001)]
    squares = [emul(n, n) for n in range(10001)]
    bits = 14
    while True:
        comp = sorted(odd_composites(bits))
        compset = set(comp)
        irr = [m for m in range(3, 1 << bits, 2) if m not in compset]
        if len(comp) >= 10000 and len(irr) >= 10000:
            break
        bits += 1
    committed = committed_counts()
    BOUNDS["cmax"] = cmax  # the engine is never asked for more than this, whatever the b-file holds
    C = engine(cmax)
    source = f"C engine, n <= {cmax}"
    if C is None and len(committed) >= bits:
        C = committed
        source = f"committed b-file (C engine not available here), n <= {len(C)}"
    elif C is None:
        C = [sum(1 for m in comp if m.bit_length() == n) for n in range(1, bits + 1)]
        source = f"Python sieve only (no C compiler), n <= {bits}"
    elif len(committed) > len(C):  # never shorten the table: keep the terms computed earlier
        require(committed[: len(C)] == C, "C engine disagrees with the committed b-file of C(n)")
        C = committed
        source = f"C engine, n <= {cmax}, equal to the committed b-file, whose {len(C)} terms are kept"
    require(C[:bits] == [sum(1 for m in comp if m.bit_length() == n) for n in range(1, bits + 1)],
            "C engine and Python sieve disagree")
    D5 = count_odd(DFA5, 1000)[1:]
    return {
        "doubling": doubling, "squares": squares, "odd_composites": comp[:10000],
        "odd_irreducibles": irr[:10000], "count_odd_composites": C, "multiples_of_5": D5,
    }, compset, bits, source


# --- facts quoted in the drafts ----------------------------------------------------

def check_facts(T, compset, bits):
    dbl, sq, C, D5 = T["doubling"], T["squares"], T["count_odd_composites"], T["multiples_of_5"]
    N = 1 << 14

    # doubling
    require(dbl[:12] == [0, 3, 6, 15, 12, 15, 30, 63, 24, 27, 30, 63], "doubling: leading terms")
    require(all(dbl[n] == emul(3, n) == eadd(n, 2 * n) for n in range(2000)), "a(n) = 3 [x] n = n [+] 2n")
    require(all(w(dbl[n]) == 2 * w(n) for n in range(10001)), "weight of n [+] n")
    require(all(dbl[2 * n] == 2 * dbl[n] and dbl[2 * n + 1] == eadd(2 * dbl[n], 3) for n in range(5000)),
            "doubling: a(2n), a(2n+1)")
    require(all(eadd(ones(k), ones(k)) == 4 ** k - 1 and eadd(1 << k, 1 << k) == 3 << k for k in range(60)),
            "doubling: a(2^k - 1), a(2^k)")
    require(all(dbl[n] >= 3 * n and (dbl[n] == 3 * n) == (n & 2 * n == 0) for n in range(10001)),
            "a(n) >= 3n with equality iff n fibbinary")
    values = {eadd(n, n) for n in range(N // 3 + 1)} & set(range(N))  # a(n) >= 3n
    require(values == {m for m in range(N) if is_multiple_of_3(m)}
            == {3 * f for f in range(N // 3 + 1) if f & 2 * f == 0 and 3 * f < N},
            "values of n [+] n = A277335")
    require(dbl[3] == dbl[5] == 15, "a(3) = a(5)")
    a162276 = []
    for n in range(1, 12):
        m = n
        while w(m) == w(n):
            m += n
        a162276.append(m)
    require(a162276[:10] == dbl[1:11] and a162276[10] == 33 and dbl[11] == 63, "comparison with A162276")
    a086799 = [n | (n - 1) for n in range(1, N + 2)]
    require(all(eadd(n, 1) == a086799[n] for n in range(N)), "n [+] 1 = A086799(n+1)")
    require(columns([2, 2, 0, 2]) == [2, 3, 2, 3, 2, 1] and dbl[11] == 63, "doubling: example")

    # squares
    require(sq[:13] == [0, 1, 4, 15, 16, 29, 60, 511, 64, 89, 116, 511, 240], "squares: leading terms")
    require(all(w(sq[n]) == w(n) ** 2 for n in range(10001)), "weight of n [x] n")
    require(all(sq[n] >= n * n and (sq[n] == n * n) == (w(n) <= 1) for n in range(10001)),
            "a(n) >= n^2 with equality iff n = 0 or a power of 2")
    require(all(sq[2 * n] == 4 * sq[n] for n in range(5001)), "squares: a(2n)")
    require(all(emul(ones(k), ones(k)) == ones(k * k) and emul(1 << k, 1 << k) == 4 ** k for k in range(40)),
            "squares: a(2^k - 1), a(2^k)")
    require(all(emul(2 ** k + 1, 2 ** k + 1) == 4 ** k + 3 * 2 ** k + 1 for k in range(2, 60)) and sq[3] == 15,
            "squares: a(2^k + 1)")
    require(sq[7] == sq[11] == 511 and len(set(sq[:7])) == 7 and sq[8:11] != [511] * 3
            and min(n for n in range(1, 100) if sq[n] in sq[:n]) == 11, "squares: first repeated value")
    require(columns([1, 2, 1]) == [1, 2, 2, 1] and sq[3] == 15, "squares: example")
    require(all(sq[n].bit_length() >= 2 * n.bit_length() - 1 for n in range(1, 10001)), "squares: length")

    # odd composites / irreducibles
    comp, irr = T["odd_composites"], T["odd_irreducibles"]
    require(comp[:14] == [15, 27, 29, 45, 51, 63, 85, 89, 95, 99, 111, 119, 123, 125], "composites: leading terms")
    require(irr[:12] == [3, 5, 7, 9, 11, 13, 17, 19, 21, 23, 25, 31], "irreducibles: leading terms")
    require(all(not is_prime(w(m)) for m in compset), "composites have composite weight")
    require(min(m for m in range(3, 1 << bits, 2) if not is_prime(w(m)) and m not in compset) == 23,
            "23 is the least odd irreducible of composite weight")
    require(factorizations(15) == {(3, 3), (3, 5)} and factorizations(27) == {(3, 9)}
            and factorizations(29) == {(5, 5)} and factorizations(45) == {(5, 9)}, "composites: examples")
    require({emul(b, c) for b in (3, 5, 9) for c in (3, 5, 9) if b.bit_length() + c.bit_length() <= 6}
            == {15, 27, 29}, "irreducibility of 23")
    require(all(m in compset for m in range(5, 1 << bits, 2) if is_multiple_of_3(m)),
            "odd multiples of 3 beyond 3 are composite")
    require(all(m in compset for m in range(7, 1 << bits, 2) if is_multiple_of_5(m)),
            "odd multiples of 5 beyond 5 are composite")
    require(all(m not in compset for m in range(3, 1 << bits, 2) if is_prime(w(m))),
            "odd numbers of prime weight are irreducible")
    require(all(m not in compset for m in range(3, 1 << bits, 2) if 2 * v2(m - 1) > m.bit_length() - 1),
            "gap criterion")
    require(all(sum(1 for m in range((1 << n - 1) + 1, 1 << n, 2) if 2 * v2(m - 1) > n - 1) == 2 ** (n // 2 - 1)
                for n in range(2, bits + 1)), "size of the gap family")
    require(emul(5, 7) == 63 == emul(3, 21) and not quotients(5, 3) and not quotients(7, 3), "3 is not prime")
    require(all(emul(2, m) == 2 * m for m in range(1000)), "2 [x] m = 2m")

    # counts
    require(C[:12] == [0, 0, 0, 1, 2, 3, 8, 15, 29, 53, 108, 196], "C(n): leading terms")
    require(D5[:12] == [0, 0, 1, 1, 1, 2, 3, 6, 10, 17, 29, 49], "D_5(n): leading terms")
    require(all(D5[n - 1] <= C[n - 1] for n in range(4, len(C) + 1)) and D5[2] > C[2], "D_5(n) <= C(n), n >= 4")
    require(all(C[n - 1] == 2 ** (n - 2) - sum(1 for m in range((1 << n - 1) + 1, 1 << n, 2) if m not in compset)
                for n in range(2, bits + 1)), "C(n) = 2^(n-2) - #irreducibles")
    require([m for m in sorted(compset) if m < 128] == [15, 27, 29, 45, 51, 63, 85, 89, 95, 99, 111, 119, 123, 125],
            "C(n): examples")
    require(all(D5[n - 1] == D5[n - 2] + D5[n - 3] + D5[n - 6] for n in range(6, 1001)), "D_5 recurrence")
    D5c = engine(BOUNDS["cmax"], 5)
    require(D5c is None or D5c == D5[: len(D5c)], "D_5: C engine vs automaton")
    require(odd_members(DFA5, 6) == [45, 63] and emul(5, 9) == 45 and emul(5, 7) == 63 == emul(5, 11)
            and runs(45) == ([1, 2, 1], [1, 1]), "D_5: example")
    require([m for m in range(1, 64, 2) if is_multiple_of_5(m)] == [5, 15, 29, 45, 63], "D_5: small multiples")
    require(not any(is_multiple_of_5(m) for m in (1, 3)), "D_5(1) = D_5(2) = 0")
    certified = multiples_dfa(2, max_carry=1)  # raises unless carry bound 1 suffices
    require(len(certified[0]) == 7 and equivalent(certified, DFA5), "D_5: certificate as described")
    require(abs(H - (log2(3) - 2 / 3)) < 1e-12 and entropy(2 / 9) < 0.7643 < H, "entropy constants")
    require(abs(D5[999] / D5[998] - LAMBDA5) < 1e-12 and LAMBDA5 > 1.7049, "growth rate of D_5")

    # proved window for the exponent of C(n)
    rates = {s: growth_rate(multiples_dfa(s)) for s in range(2, 7)}  # exact roots, a = 2^s + 1
    gammas = {s: float(gam) for s, (lam, gam) in rates.items()}
    carry = next(K for K in range(1, 7) if certifies(6, K))
    dfa65 = multiples_dfa(6)
    x, theta, E = no111_exponent()
    require(abs(float(rates[2][0]) - LAMBDA5) < 1e-12 and all(gammas[s] < gammas[s + 1] for s in range(2, 6)),
            "growth rates of the multiples of 2^s + 1")
    require(all(d - 1 <= c for d, c in zip(count_odd(dfa65, len(C))[1:], C)), "D_65(n) - 1 <= C(n)")
    require((f"{x:.6f}", f"{theta:.6f}", f"{E:.6f}") == ("0.808173", "0.705340", "0.874665")
            and abs(entropy(theta) - E) < 1e-9 and entropy(1 / 4) < E, "No-111 optimum")
    require(all(emul(1 | 1 << r, 1 | 1 << r | 1 << 2 * r) == emul(1 | 1 << r, eadd(1 | 1 << 2 * r, 2 << r))
                for r in range(1, 60)), "No-111 exchange identity")
    slope = log2(C[-1] / C[-2])
    require(len(C) < 30 or slope < gammas[6], "local slope below the proved lower bound")
    BOUNDS.update(gammas=gammas, lam65=float(rates[6][0]), states65=len(dfa65[0]), carry65=carry,
                  x=x, theta=theta, E=E, slope=slope)


def certifies(s, K):
    try:
        multiples_dfa(s, max_carry=K)
    except ValueError:
        return False
    return True


def cross_check_online():
    def bfile(anum):
        url = f"https://oeis.org/{anum}/b{anum[1:]}.txt"
        request = urllib.request.Request(url, headers={"User-Agent": "exclusion-arithmetic"})
        text = urllib.request.urlopen(request, timeout=60).read().decode()
        return dict(tuple(map(int, line.split()[:2])) for line in text.splitlines()
                    if line.strip() and not line.startswith("#"))

    b = bfile("A162276")
    require(all(b[n] == eadd(n, n) for n in range(1, 11)) and b[11] == 33, "online: A162276")
    b = bfile("A086799")
    require(all(b[n + 1] == eadd(n, 1) for n in range(0, max(b))), "online: A086799")
    b = bfile("A277335")
    require(all(is_multiple_of_3(v) for v in b.values())
            and sorted(b.values()) == [m for m in range(max(b.values()) + 1) if is_multiple_of_3(m)],
            "online: A277335")
    b = bfile("A052294")
    require(all(is_prime(w(v)) for v in b.values()), "online: A052294")
    print("online cross-checks against oeis.org: A162276, A086799, A277335, A052294 fetched and compared")


