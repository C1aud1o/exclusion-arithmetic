#!/usr/bin/env python3
"""Generate the OEIS submission package: drafts, b-files, and their verification.

    python scripts/generate_oeis.py [--cmax 31] [--a KEY=A123456 ...] [--repo URL] [--online]

Writes oeis/drafts/<k>_<key>.txt and oeis/bfiles/b_<key>.txt for the six
sequences, computing every term with the library, and checks that
  * each DATA line is a prefix of its b-file and fits the OEIS length limit,
  * each OFFSET is correct,
  * every statement made in COMMENTS / FORMULA / EXAMPLE holds on the data,
  * the Python and PARI/GP programs printed in the drafts, run as separate
    processes, reproduce the terms (PARI is skipped if `gp` is not installed).

--cmax N   count composites up to N bits with the C engine (default 31;
           N = 37 needs 8 GiB and about 7 minutes on 4 cores).  The committed
           b-file of C(n) is never shortened: if it has more than N terms they
           are kept, after checking that the engine reproduces the first N.
           If the engine cannot be built or run, the committed b-file is reused.
--a        A-numbers already assigned, e.g. --a doubling=A390001.  Batch 1
           drafts never contain a placeholder; batch 2 drafts show the batch 1
           numbers still missing as A??????(key) and mention other batch 2
           sequences only once their numbers are given
--online   also compare the cited OEIS entries with their b-files on oeis.org
"""

