def run_python(code):
    out = subprocess.run([sys.executable, "-c", code], check=True, capture_output=True, text=True).stdout
    return [ast.literal_eval(line) for line in out.strip().splitlines()]


def run_gp(lines):
    """Evaluate the lines in one gp session; return the printed value of each bare expression."""
    script = "\n".join(l if re.match(r"\w+\([\w, ]*\) = ", l) else f"print({l})" for l in lines)
    out = subprocess.run(["gp", "-q", "--default", "parisizemax=1G"], input=script + "\n",
                         check=True, capture_output=True, text=True).stdout
    return [ast.literal_eval(line) for line in out.strip().splitlines()]


def check_programs(T):
    have_gp = shutil.which("gp") is not None
    status = {}
    for key, (gp_lines, py_code, count) in PROGRAMS.items():
        terms = T[key]
        if count is None:  # the program prints every term below 2^9
            expected = [m for m in terms if m < 512]
        else:
            expected = terms[:count]
        py = run_python(py_code)
        require(py == [expected], f"{key}: Python program output")
        if have_gp:
            gp = run_gp(gp_lines)
            require(len(gp) >= 1 and gp[-1] == expected, f"{key}: PARI program output")
            for got in gp[:-1]:  # additional programs, e.g. the generating function
                require(len(got) >= 16 and got == terms[: len(got)], f"{key}: PARI program output")
        status[key] = "Python OK, PARI " + ("OK" if have_gp else "NOT RUN (gp not installed)")
    return status


