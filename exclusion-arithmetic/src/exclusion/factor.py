"""Divisibility and factorisation in S.

Facts used throughout (a, b non-zero; len = bit length):

* w(a [x] b) = w(a) w(b)  and  v2(a [x] b) = v2(a) + v2(b);
* len(a [x] b) >= len a + len b - 1   (lengths are superadditive);
* (a [x] b) mod 2^m depends only on a mod 2^m and b mod 2^m.

The only unit is 1.  An element n >= 2 is *irreducible* if n = a [x] b forces
a = 1 or b = 1, and *composite* otherwise.  Since 2 [x] m = 2m, an even n is
composite exactly when n >= 4; all the structure sits in the odd elements.
S is not cancellative (3 [x] 3 = 3 [x] 5 = 15), so quotients are sets.
"""

from functools import lru_cache

from .core import eadd, emul, g, v2, w

__all__ = [
    "quotients", "divides", "divisors", "is_composite", "is_irreducible",
    "factorizations", "odd_composites", "gap_irreducible", "G",
]


def quotients(n, d):
    """The set of all c with d [x] c = n  (d >= 1).

    2-adic lifting: the low m bits of d [x] c depend only on the low m bits of
    c, so c is built upwards one bit at a time, keeping every prefix that still
    agrees with n.  Weight and length bound the search.
    """
    if d < 1 or n < 0:
        raise ValueError("need d >= 1 and n >= 0")
    if n == 0:
        return {0}
    shift = v2(n) - v2(d)
    if shift < 0 or w(n) % w(d):
        return set()
    n >>= v2(n)
    d >>= v2(d)
    top = n.bit_length() - d.bit_length()  # c has at most top + 1 bits
    if top < 0:
        return set()
    weight = w(n) // w(d)
    prefixes = [1]
    for m in range(1, top + 1):
        mask = (2 << m) - 1
        prefixes = [
            c
            for p in prefixes
            for c in (p, p | 1 << m)
            if w(c) <= weight and not (emul(d, c) ^ n) & mask
        ]
    return {c << shift for c in prefixes if emul(d, c) == n}


def divides(d, n):
    """True iff n = d [x] c for some c."""
    return n == 0 if d == 0 else bool(quotients(n, d))


def _odd_splits(n):
    """All (d, c) with d [x] c = n, d and c odd, 1 < len d <= len c  (n odd)."""
    half = (n.bit_length() + 1) // 2  # the shorter factor has at most this many bits
    for d in range(3, 1 << half, 2):
        if 1 < w(d) < w(n) and w(n) % w(d) == 0:
            for c in quotients(n, d):
                if c.bit_length() >= d.bit_length():
                    yield d, c


def divisors(n):
    """Sorted list of all d with d | n  (n >= 1)."""
    if n < 1:
        raise ValueError("need n >= 1")
    odd = n >> v2(n)
    ds = {1, odd}
    for d, c in _odd_splits(odd):
        ds |= {d, c}
    return sorted(d << k for d in ds for k in range(v2(n) + 1))


def is_composite(n):
    """True iff n = a [x] b with a, b >= 2."""
    if n < 4:
        return False
    if n % 2 == 0:
        return True
    return next(_odd_splits(n), None) is not None


def is_irreducible(n):
    """True iff n >= 2 and n is not composite."""
    return n >= 2 and not is_composite(n)


@lru_cache(maxsize=None)
def factorizations(n):
    """All factorisations of n >= 1 into irreducibles, as a set of sorted tuples.

    2 = x is prime, so every factorisation contains exactly v2(n) factors 2.
    """
    if n < 1:
        raise ValueError("need n >= 1")
    if n % 2 == 0:
        k = v2(n)
        return frozenset((2,) * k + f for f in factorizations(n >> k))
    if n == 1:
        return frozenset({()})
    found = set()
    for d, c in _odd_splits(n):
        for fd in factorizations(d):
            for fc in factorizations(c):
                found.add(tuple(sorted(fd + fc)))
    return frozenset(found or {(n,)})


def odd_composites(nbits):
    """Set of all odd composites with at most nbits bits (a sieve by products).

    For each odd c > 1 the products b [x] c are generated by a depth-first walk
    over the bits of b: (b + x^k) [x] c = (b [x] c) [+] (c << k).  [+] never
    clears a bit, so a partial product longer than nbits is abandoned.
    """
    limit = 1 << nbits
    found = set()

    def walk(c, p, k, kmax):
        for j in range(k, kmax + 1):
            q = eadd(p, c << j)
            if q < limit:
                found.add(q)
                walk(c, q, j + 1, kmax)

    for lc in range(2, nbits):
        for c in range((1 << lc - 1) + 1, 1 << lc, 2):
            walk(c, c, 1, min(lc - 1, nbits - lc))  # len b <= len c
    return found


def gap_irreducible(n):
    """Gap Lemma criterion: n odd, n >= 3 and 2 g(n) > len(n) - 1.

    If n = a [x] b with a, b odd and > 1, then g(n) = min(g(a), g(b)) and
    len(n) - 1 >= (len a - 1) + (len b - 1) >= g(a) + g(b) >= 2 g(n).
    Hence every n passing this test is irreducible.
    """
    return n >= 3 and n % 2 == 1 and 2 * g(n) > n.bit_length() - 1


def G(n):
    """G_n: the n-bit elements certified irreducible by the Gap Lemma.

    |G_n| = 2^(floor(n/2) - 1) for n >= 2.
    """
    if n < 2:
        return []
    top = 1 << n - 1
    out = [top | 1]
    for gap in range((n - 1) // 2 + 1, n - 1):
        step = 2 << gap
        out += range(top | 1 << gap | 1, 2 * top, step)
    return sorted(out)
