"""Core operations of Exclusion Arithmetic.

S = N_0[x] / <2 ~ 1 + x> is the commutative semiring of polynomials with
non-negative integer coefficients modulo the congruence generated by
2 = 1 + x.  Rewriting 2 x^k -> x^k + x^(k+1) is confluent and terminating, so
every class has a unique normal form with coefficients in {0, 1}.  Reading a
normal form as a binary numeral (x -> 2) identifies S with the non-negative
integers; `eadd` and `emul` are the induced sum and product.

Normalisation is the Lindley recursion: a column holding t units keeps one
unit (if t > 0) and passes the other t - 1 upwards,

    digit_k = [c_k + p_k >= 1],        c_{k+1} = max(c_k + p_k - 1, 0),

where p_k is the k-th coefficient and c_0 = 0.  For a sum, p_k = a_k + b_k.
All arithmetic is on Python integers, so there is no word size to overflow.
"""

from math import inf

__all__ = ["eadd", "emul", "epow", "w", "v2", "g", "normalize"]


def _bits(a):
    """Binary digits of a >= 0 as a string, least significant first."""
    if a < 0:
        raise ValueError("elements of S are non-negative integers")
    return format(a, "b")[::-1]


def normalize(coefficients):
    """Normal form of sum(p_k x^k), given the p_k >= 0 for k = 0, 1, 2, ..."""
    digits = []
    c = 0
    for p in coefficients:
        t = c + p
        if t:
            digits.append("1")
            c = t - 1  # c_{k+1} = max(c_k + p_k - 1, 0), case t >= 1
        else:
            digits.append("0")  # ... and case t = 0: the carry stays 0
    digits.append("1" * c)  # above the top coefficient every column takes one unit
    return int("".join(digits)[::-1] or "0", 2)


def eadd(a, b):
    """a [+] b: the exact Lindley recursion c_{k+1} = max(c_k + a_k + b_k - 1, 0).

    Theta(n) bit operations for n-bit arguments.
    """
    sa, sb = _bits(a), _bits(b)
    n = max(len(sa), len(sb))
    return normalize(
        (x == "1") + (y == "1") for x, y in zip(sa.ljust(n, "0"), sb.ljust(n, "0"))
    )


def emul(a, b):
    """a [x] b: normal form of the polynomial product.

    The coefficients of the product in N_0[x] are read off one ordinary
    big-integer product (Kronecker substitution): each coefficient is at most
    min(w(a), w(b)) < 2^s, so spacing the bits of a and b by s positions keeps
    the columns from interfering.  One Lindley pass then normalises.
    """
    sa, sb = _bits(a), _bits(b)
    if not (a and b):
        return 0
    s = min(a.bit_count(), b.bit_count()).bit_length()
    pad = "0" * (s - 1)
    prod = int(pad.join(sa)[::-1], 2) * int(pad.join(sb)[::-1], 2)
    sp = format(prod, "b")
    sp = sp.zfill(-(-len(sp) // s) * s)
    return normalize(int(sp[i - s : i], 2) for i in range(len(sp), 0, -s))


def epow(a, e):
    """a [x] a [x] ... [x] a (e factors); epow(a, 0) = 1."""
    if e < 0:
        raise ValueError("negative exponent")
    result = 1
    while e:
        if e & 1:
            result = emul(result, a)
        a = emul(a, a)
        e >>= 1
    return result


def w(a):
    """Hamming weight = value at x = 1.  A semiring homomorphism S -> (N_0, +, *)."""
    return a.bit_count()


def v2(a):
    """2-adic valuation = order of vanishing at x = 0; v2(0) = inf.

    A semiring homomorphism S -> (N_0 u {inf}, min, +).
    """
    return (a & -a).bit_length() - 1 if a else inf


def g(a):
    """Gap: distance between the two lowest 1-bits of a; inf if w(a) < 2.

    For odd a > 1 this is v2(a - 1).  g(a [x] b) = min(g(a), g(b)) for a, b != 0.
    """
    low = a & -a
    return v2(a ^ low) - v2(low) if a ^ low else inf
